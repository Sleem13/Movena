export function rehabText(locale, value) {
  if (locale !== "ar" || typeof value !== "string") return value;
  return ARABIC_TEXT[value] || value;
}

export function localizeRehabConditions(conditions, locale) {
  if (locale !== "ar") return conditions;
  return conditions.map((condition) => {
    const displayName = REHAB_CONDITION_AR[condition.id] || condition.name;
    const displayCategory = rehabText(locale, condition.category);
    const displayBodyRegion = rehabText(locale, condition.body_region);
    return {
      ...condition,
      display_name: displayName,
      display_category: displayCategory,
      display_body_region: displayBodyRegion,
      search_text: `${condition.search_text || ""} ${displayName} ${displayCategory} ${displayBodyRegion}`,
    };
  });
}
